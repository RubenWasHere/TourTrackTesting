// `main()` is marked `async` because some setup steps below (like connecting
// to Firebase) take time to complete — they don't finish instantly.
// `async` lets us use `await` to pause and wait for them before continuing.
void main() async {
  // Normally Flutter sets up its internal "engine" automatically right
  // before running the app. But since we need to talk to native Android/iOS
  // code (Firebase, orientation settings) BEFORE runApp() is called,
  // we have to manually tell Flutter "get ready now" using this line.
  // Any time you call a native/plugin feature before runApp(), you need this.
  WidgetsFlutterBinding.ensureInitialized();

  await dotenv.load(fileName: '.env');

  // Connects this app to our actual Firebase project (the one we set up with
  // `flutterfire configure`). `DefaultFirebaseOptions.currentPlatform`
  // automatically picks the correct config depending on whether we're
  // running on Android or iOS — we don't have to manually check platform.
  //
  // We `await` this because the rest of the app (like checking if someone
  // is logged in) depends on Firebase already being connected. If we didn't
  // wait, the app might try to use Firebase before it's ready and crash.
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  await LocalNotificationService.initialise();
  await NotificationService().initialise();

  // Locks the app to portrait mode only (blocks sideways/landscape rotation).
  // TourTrack's UI is designed for portrait, so we don't want users
  // accidentally rotating into a broken-looking landscape layout.
  await SystemChrome.setPreferredOrientations([
    DeviceOrientation.portraitUp,
    DeviceOrientation.portraitDown,
  ]);
  // Initializes the Google Sign-In plugin so we can use it in the app.
  await GoogleSignIn.instance.initialize(
    serverClientId:
        '222564274719-cuc03bmfl20iboluql89jbb5nq2q3ued.apps.googleusercontent.com',
  );

  // Initializes the Facebook Sign-In plugin so we can use it in the app.
  await FacebookAuth.instance.webAndDesktopInitialize(
    appId: "2575055626345519",
    cookie: true,
    xfbml: true,
    version: "v12.0",
  );

  // This is the actual line that starts the app and puts something on
  // screen. Everything above this line is just setup/config that needs
  // to happen first — nothing visual has appeared yet until this runs.
  runApp(const MyApp());
}

// MyApp is the ROOT widget of the whole app. Think of it as the container
// that holds app-wide settings (theme, title, starting screen) — it isn't
// a "screen" itself, more like the app's overall configuration wrapper.
class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    // MaterialApp is a special Flutter widget that sets up everything an
    // app needs to behave like a proper Android/iOS app: theming,
    // navigation, localization support, etc. Almost every Flutter app
    // starts with a MaterialApp at the root.
    return MaterialApp(
      title:
          'TourTrack', // Shown in the OS task-switcher, not on-screen in the app itself
      debugShowCheckedModeBanner:
          false, // Hides the red "DEBUG" ribbon in the corner while developing
      // ---- THEME ----
      // This defines app-wide default styling. Any widget (buttons, app bars,
      // etc.) will automatically use these colors/fonts UNLESS we manually
      // override them on that specific widget.
      theme: ThemeData(
        fontFamily:
            'Poppins', // Sets Poppins as the default font everywhere in the app
        // ColorScheme.fromSeed takes ONE color (our brand yellow) and
        // automatically generates a full matching palette from it —
        // primary color, accents, etc. This keeps the whole app feeling
        // visually consistent without us manually picking a dozen colors.
        colorScheme: ColorScheme.fromSeed(
          seedColor: const Color(0xFFFFDE59), // TourTrack's brand yellow
        ),

        // By default, Material 3's generated color scheme would tint the
        // background slightly (not pure white). We override that here so
        // every screen's background is guaranteed pure white regardless
        // of what the seed color generates.
        scaffoldBackgroundColor: Colors.white,

        textSelectionTheme: TextSelectionThemeData(
          cursorColor: const Color(0xFF1F4E9E), // TourTrack's brand blue
          selectionColor: const Color(
            0xFF1F4E9E,
          ).withValues(alpha: 0.3), // the highlighted text background
          selectionHandleColor: const Color(
            0xFF1F4E9E,
          ), // the two draggable teardrop handles
        ),

        useMaterial3:
            true, // Opts into the newer Material Design 3 look and behaviors
      ),

      // This is the very FIRST screen the user sees when the app opens.
      // Right now it's SplashScreen — from there, SplashScreen itself
      // decides (based on Firebase login state) where to send the user next.
      home: const SplashScreen(),
    );
  }
}

// ============================================================
// MyHomePage — currently a placeholder "logged in" screen.
// This is where a user lands if Firebase detects they're already
// logged in (see splash_screen.dart's navigation logic).
//
// TODO: eventually replace this with real tourist/guide home screens
// once those are built — this is just a temporary stand-in so we have
// SOMETHING to navigate to for testing purposes.
// ============================================================
class MyHomePage extends StatelessWidget {
  const MyHomePage({super.key});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      // Scaffold = Flutter's standard "page layout" widget.
      // Gives us pre-built slots for common screen parts
      // like an app bar and a body, instead of building
      // that structure manually every time.
      appBar: AppBar(
        title: const Text('TourTrack'),
        actions: [
          IconButton(
            tooltip: 'Log out',
            icon: const Icon(Icons.logout),
            onPressed: () async {
              await AuthService().signOut();
              if (!context.mounted) return;
              Navigator.of(context).pushAndRemoveUntil(
                MaterialPageRoute(builder: (_) => const RoleSelectionScreen()),
                (_) => false,
              );
            },
          ),
        ],
      ),
      body: const Center(child: Text('Welcome to TourTrack')),
    );
  }
}
