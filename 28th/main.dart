// ============================================================
// main.dart
// This is the ENTRY POINT of the entire app — every Flutter app
// has exactly one of these. There is only ever one main.dart,
// no matter how many screens the app has.
//
// This file's jobs are:
//   1. Set up anything the app needs BEFORE it can show anything
//      on screen (Firebase, orientation lock, etc.)
//   2. Define the root widget (MyApp) that configures app-wide
//      settings like theme, title, and which screen shows first.
// ============================================================

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:google_sign_in/google_sign_in.dart';
